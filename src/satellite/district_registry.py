def normalize_district_name(district_name: str) -> str:
    """Normalizes any district name or alias to canonical registry name."""
    clean = district_name.strip().lower()
    if clean in DISTRICT_ALIASES:
        return DISTRICT_ALIASES[clean]
    for canonical in TAMIL_NADU_DISTRICTS_REGISTRY.keys():
        if canonical.lower() == clean:
            return canonical
    return district_name.strip().title()


def get_all_districts() -> List[str]:
    """Returns sorted list of all 38 Tamil Nadu districts."""
    return sorted(list(TAMIL_NADU_DISTRICTS_REGISTRY.keys()))


def get_parent_district(district_name: str) -> str:
    """Maps bifurcated or new districts to their historical statistical parent district."""
    canonical = normalize_district_name(district_name)
    prof = TAMIL_NADU_DISTRICTS_REGISTRY.get(canonical)
    if prof and "parent_district" in prof:
        return prof["parent_district"]
    return canonical


def get_district_profile(district_name: str) -> Optional[Dict[str, Any]]:
    """Retrieves full geospatial, agro-climatic, hydrological and soil profile for a district."""
    canonical = normalize_district_name(district_name)
    data = TAMIL_NADU_DISTRICTS_REGISTRY.get(canonical)
    if not data:
        return None
    return {
        "district": canonical,
        "centroid": {"latitude": data["lat"], "longitude": data["lon"]},
        "primary_sentinel2_tile": data["primary_tile"],
        "primary_sentinel1_orbit": data.get("primary_s1_orbit", 54),
        "parent_district": data.get("parent_district", canonical),
        **data
    }


def get_district_polygon_wkt(district_name: str) -> Optional[str]:
    """Generates WKT Polygon from district bounding box for STAC / OData query."""
    prof = get_district_profile(district_name)
    if not prof:
        return None
    min_lon, min_lat, max_lon, max_lat = prof["bbox"]
    return f"POLYGON(({min_lon} {min_lat}, {max_lon} {min_lat}, {max_lon} {max_lat}, {min_lon} {max_lat}, {min_lon} {min_lat}))"
